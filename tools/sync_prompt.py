"""Write the Text mode system prompt into the website's proxy so both stay in sync.

    python tools/sync_prompt.py [path/to/site]

The app keeps the prompt for "use my own key" mode; the proxy owns it for
everyone else. tests/test_ai_proxy.py fails when the two differ.
"""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))


def render() -> str:
    from assist.ai_binder import PROMPT_VERSION, SYSTEM_PROMPT

    digest = hashlib.sha256(SYSTEM_PROMPT.encode("utf-8")).hexdigest()
    return (
        "'use strict';\n"
        "// GENERATED by Keyware tools/sync_prompt.py from assist/ai_binder.py. Do not edit by hand.\n"
        f"const PROMPT_VERSION = {json.dumps(PROMPT_VERSION)};\n"
        f"const PROMPT_SHA256 = {json.dumps(digest)};\n"
        f"const SYSTEM_PROMPT = {json.dumps(SYSTEM_PROMPT, ensure_ascii=False)};\n"
        "module.exports = { PROMPT_VERSION, PROMPT_SHA256, SYSTEM_PROMPT };\n"
    )


def main() -> int:
    site = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "site"
    target = site / "api" / "_lib" / "prompt.js"
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(render(), encoding="utf-8", newline="\n")
    print(target)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
